#!/usr/bin/env python3
"""Writes src/casefold.s: the case folding the case-insensitive search matches with, and for
every two-byte character whose fold group has exactly one other member, the first two bytes of
both.

usage: tools/gen-casefold.py > src/casefold.s"""
import sys


def fold(cp):
    f = chr(cp).casefold()
    if len(f) != 1:
        return cp
    n = ord(f)
    try:
        a = len(chr(cp).encode())
        b = len(chr(n).encode())
    except UnicodeEncodeError:    # a surrogate: not a character
        return cp
    # only folds of the same byte length keep a match nlen bytes long; the others stay as they are
    if a != b:
        return cp
    return n


def main():
    out = sys.stdout
    # one fold per character; sorted by codepoint for a binary search
    folds = []
    for cp in range(0x110000):
        f = fold(cp)
        if f != cp:
            folds.append((cp, f))
    # for a two-byte character (U+0080 .. U+07FF): the members folding to the same character. With
    # exactly two (я and Я), a search by the first two bytes finds both; with more (σ, ς and Σ)
    # there is nothing to pack: candidates fall back to every character as long.
    groups = {}
    for cp in range(0x80, 0x800):
        groups.setdefault(fold(cp), []).append(cp)
    variants = []
    for members in groups.values():
        if len(members) != 2:
            continue
        packed = 0
        shift = 0
        for cp in members:
            b = chr(cp).encode()
            packed |= b[0] << shift
            shift += 8
            packed |= b[1] << shift
            shift += 8
        for cp in members:
            variants.append((cp, packed))
    variants.sort()
    out.write('# case folding for the case-insensitive search, generated by\n')
    out.write('# tools/gen-casefold.py from Unicode; do not edit.\n')
    out.write('.include "unn.inc"\n.section .rodata\n.p2align 3\n')
    out.write('.globl casefold_count, fold_variant_count\n')
    out.write('casefold_count: .quad %d\n' % len(folds))
    out.write('# sorted by codepoint: character, its fold (the fold is a single character of as many\n')
    out.write('# bytes as the character itself, so a match stays within the needle\'s length)\n')
    out.write('casefold_table:\n')
    for cp, f in folds:
        out.write('    .long 0x%06x, 0x%06x\n' % (cp, f))
    out.write('.p2align 3\nfold_variant_count: .quad %d\n' % len(variants))
    out.write('# sorted by codepoint: character, the first two bytes of it and of the other member of\n')
    out.write('# its fold group, packed dl to the highest byte\n')
    out.write('fold_variant_table:\n')
    for cp, packed in variants:
        out.write('    .long 0x%06x, 0x%08x\n' % (cp, packed))
    # the generated file is not only tables: the two binary-search helpers over them are
    # appended as assembly text, so the search side can call case_fold/fold_variants directly
    fns = r'''
# case_fold(cp) -> its fold, or cp itself when it does not fold to a single character of as many
# bytes; preserves every register but rax
FN case_fold
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    mov r12d, edi
    xor ebx, ebx                  # low row
    mov r10, [rip + casefold_count] # row after the last
1:  cmp rbx, r10
    jae 3f
    lea r8, [rbx + r10]
    shr r8, 1                     # middle row
    mov r9, r8
    shl r9, 3                     # its offset in the table
    lea rax, [rip + casefold_table]
    cmp r12d, dword ptr [rax + r9]
    je 2f
    ja 11f
    mov r10, r8
    jmp 1b
11: lea rbx, [r8 + 1]
    jmp 1b
2:  mov eax, dword ptr [rax + r9 + 4]
    jmp .Lcf_ret
3:  mov eax, r12d                 # it does not fold
.Lcf_ret:
    pop r12
    pop rbx
    pop rbp
    ret

# fold_variants(cp) -> rax 1 and edx, the first two bytes of the two members of cp's fold group
# packed, or rax 0 when there is not exactly one other member; preserves the rest
FN fold_variants
    push rbp
    mov rbp, rsp
    push rbx
    push r12
    mov r12d, edi
    xor ebx, ebx                  # low row
    mov r10, [rip + fold_variant_count] # row after the last
1:  cmp rbx, r10
    jae 3f
    lea r8, [rbx + r10]
    shr r8, 1                     # middle row
    mov r9, r8
    shl r9, 3                     # its offset in the table
    lea rax, [rip + fold_variant_table]
    cmp r12d, dword ptr [rax + r9]
    je 2f
    ja 11f
    mov r10, r8
    jmp 1b
11: lea rbx, [r8 + 1]
    jmp 1b
2:  mov edx, dword ptr [rax + r9 + 4]
    mov eax, 1
    jmp .Lfv_ret
3:  xor eax, eax
    xor edx, edx
.Lfv_ret:
    pop r12
    pop rbx
    pop rbp
    ret
'''
    out.write(fns)


main()
